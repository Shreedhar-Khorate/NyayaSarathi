# ── TEST 10: Arrest Dates Are Not Incorrectly Selected from First Arbitrary Date
def test_arrest_date_not_selected_from_arbitrary_first_date():
    from services.drafts_service import _extract_arrest_date

    # facts with first date as contract date, and NO arrest date
    facts_no_arrest = "Parties entered into contract on 01.01.2023. Dispute arose on 05.05.2023."
    important_dates = ["01.01.2023", "05.05.2023"]

    arrest_dt = _extract_arrest_date(facts_no_arrest, important_dates)
    # Must NOT select 01.01.2023 as arrest date!
    assert arrest_dt is None

    # Labeled arrest date in important_dates
    important_dates_labeled = ["Contract: 01.01.2023", "Arrested on: 10.08.2024"]
    arrest_dt_labeled = _extract_arrest_date(facts_no_arrest, important_dates_labeled)
    assert arrest_dt_labeled == "10.08.2024"


# ── TEST 11: Unrelated Years Do Not Determine Statutory Regime ────────────────
def test_unrelated_years_do_not_determine_statutory_regime():
    from services.drafts_service import _evaluate_statutory_era

    # Narrative mentions past precedent (2012) and company registered in 1995,
    # but the alleged FIR/incident date is 15.08.2024!
    facts = (
        "ABC Corp was founded in 1995. In landmark precedent (2012) 1 SCC 40, principles were laid down. "
        "The alleged FIR was registered on 15.08.2024 for an incident occurring on 10.08.2024."
    )
    era, warnings = _evaluate_statutory_era(facts=facts)
    # Must be BNS_BNSS because the relevant offence/FIR date is August 2024, NOT IPC because of 1995 or 2012!
    assert era == "BNS_BNSS"
    assert "Bharatiya Nyaya Sanhita" in warnings[0]


