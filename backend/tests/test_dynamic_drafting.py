# ── TEST 3: LLM Failure Does NOT Return a Static Draft ────────────────────────
def test_llm_failure_does_not_return_static_draft():
    with patch("services.drafts_service._call_llm_json", side_effect=RuntimeError("Groq / Gemini API timeout or offline")):
        payload = {
            "document_type": "legal_notice",
            "facts": "Employer wrongfully withheld severance pay and gratuity for 6 months after lawful resignation.",
            "target_language": "en",
        }
        res = client.post("/api/drafts/generate", json=payload)
        # MUST return an explicit error (502 Bad Gateway), NEVER 200 with a static fallback draft
        assert res.status_code == 502
        assert "Legal draft generation failed" in res.json()["error"]
        assert "No static fallback is permitted" in res.json()["error"]


