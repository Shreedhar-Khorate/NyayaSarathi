"""
Statutory Mapping Service — Dynamic Indian Statutory Concordance
Dynamically maps and cross-references statutory sections between old codes
(IPC, CrPC, Indian Evidence Act) and new criminal laws (BNS, BNSS, BSA, 2023)
or applicable special enactments using AI inference.
"""
from schemas.statutes import StatuteMapResponse
from services.war_room_service import _call_llm_json
from logger import get_logger

log = get_logger("nyayasarathi.statutes_service")


def map_statute(section: str) -> StatuteMapResponse:
    """
    Dynamically maps a statutory section (e.g. IPC to BNS, CrPC to BNSS, Evidence Act to BSA)
    using AI statutory inference.
    """
    clean_section = section.strip()

    system_prompt = (
        "You are an expert Indian Legislative Draftsman and Statutory Registrar.\n"
        "Map the requested statutory section between the prior regime (e.g. IPC, 1860, CrPC, 1973, Evidence Act, 1872) "
        "and the 2023 enactments (Bharatiya Nyaya Sanhita, Bharatiya Nagarik Suraksha Sanhita, Bharatiya Sakshya Adhiniyam) "
        "or explain its corresponding provision under Indian law.\n"
        "Return strictly a JSON object with keys:\n"
        "- input_section: the input section string as requested (e.g. 'IPC 302' or 'Section 41A CrPC')\n"
        "- mapped_section: the corresponding enacted section under BNS / BNSS / BSA (e.g. 'Section 103(1) BNS, 2023' or 'Section 35(3) BNSS, 2023')\n"
        "- notes: precise explanation of ingredients, statutory change, sentencing, or continuity."
    )

    user_prompt = f"Statutory Section to map: {clean_section}"

    try:
        data, provider, model, t_in, t_out = _call_llm_json(system_prompt, user_prompt)
        if isinstance(data, dict) and data.get("mapped_section"):
            return StatuteMapResponse(
                input_section=str(data.get("input_section", clean_section)),
                mapped_section=str(data.get("mapped_section")),
                notes=str(data.get("notes", "Statutory cross-reference generated by NyayaSarathi Legal Engine.")),
            )
    except Exception as e:
        log.error(f"Statutory mapping failed: {e}")

    return StatuteMapResponse(
        input_section=clean_section,
        mapped_section=f"Section {clean_section} (Statutory review indicated)",
        notes=f"Verify corresponding enactment under the Bharatiya Nyaya Sanhita / BNSS / BSA, 2023 or relevant special act.",
    )
